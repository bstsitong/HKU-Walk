const model = require('../guideReaderData.ts');
const Reader = require('../BuiltinGuideReader.tsx').default;
const { localizedGuideArticle } = require('../guideLocalization.ts');
const { setCurrentLanguage } = require('../localization.ts');
const originals = require('../server/guide/student_guide_articles.json');
const articles = originals.map((a,i) => ({...a,id:String(i),markdown:true,isCommunity:false}));
const find = (r,id) => r.root.findAll(n => typeof n.type === 'string' && n.props.testID === id);
const press = node => act(async () => node.props.onPress());
const mount = async props => { let r; await act(async () => { r=create(React.createElement(Reader,props)); }); return r; };
const unmount = r => act(async () => r.unmount());
async function run() {
  const [links,handbook,food,groups] = articles;
  assert.deepEqual(articles.map(model.readerKind), ['links','handbook','food','groups']);
  assert.equal(model.readerKind({...links,isCommunity:true}),undefined);
  assert.equal(model.readerKind({...links,title:'Future submitted guide'}),undefined);
  const urls = [];
  for (language of ['zh-Hans','zh-Hant','en']) {
    setCurrentLanguage(language);
    const local = articles.map(a => localizedGuideArticle(a,language));
    const linksByGroup = model.quickLinkGroups(links,local[0]);
    assert.equal(linksByGroup.length,7);
    assert.equal(linksByGroup.flatMap(g=>g.links).length,17);
    assert.equal(linksByGroup[0].links[0].alias,'Moodle');
    const currentUrls=linksByGroup.flatMap(g=>g.links.map(l=>l.url)).sort();
    if (urls.length) assert.deepEqual(currentUrls,urls); else urls.push(...currentUrls);
    assert.equal(model.handbookEntries(handbook,local[1]).length,17);
    const steps=model.orderedGuideSteps(local[1].sourcePages['八校通申请'].body);
    assert.equal(steps.steps.length,7);
    assert.equal(steps.steps.flatMap(s=>s.images).length,4);
    const foods=model.foodEntries(food,local[2]);
    assert.equal(foods.length,46,`${language} food count`);
    assert.equal(new Set(foods.map(f=>f.id)).size,46);
    assert.equal(foods.filter(f=>f.pageKey).length,2);
    assert.equal(model.groupEntries(groups,local[3]).length,11);
    const r=await mount({source:links,onBack(){},footer:React.createElement('Footer')});
    assert.equal(r.root.findAllByProps({accessibilityRole:'link'}).length,17);
    assert.equal(r.root.findAllByType('Markdown').length,0,'Quick links have no explanatory copy');
    assert.equal(find(r,'reader-post-end')[0].children[0].type,'Footer');
    await act(async()=>find(r,'reader-search')[0].props.onChangeText('Moodle'));
    assert.equal(r.root.findAllByProps({accessibilityRole:'link'}).length,1);
    await press(r.root.findByProps({accessibilityRole:'link'}));
    assert.equal(opened.at(-1),urls.find(url=>/moodle/i.test(url)));
    await unmount(r);
  }
  language='zh-Hans'; setCurrentLanguage(language);
  const h=await mount({source:handbook,onBack(){},footer:React.createElement('Footer')});
  await act(async()=>find(h,'reader-search')[0].props.onChangeText('八校通'));
  const julacEntry=model.handbookEntries(handbook,handbook).find(e=>e.pageKey==='八校通申请');
  const entry=find(h,`guide-section-${julacEntry.id}`)[0];
  await press(entry);
  assert.equal(find(h,'guide-reader-detail').length,1);
  assert.equal(h.root.findAll(n=>typeof n.type==='string' && /^guide-step-/.test(n.props.testID)).length,7);
  assert.equal(find(h,'guide-reader-detail')[0].children.at(-1).props.testID,'reader-post-end');
  await press(find(h,'guide-directory')[0]);
  assert.equal(find(h,'reader-search')[0].props.value,'八校通','Back to contents retains search');
  await unmount(h);
  const g=await mount({source:groups,onBack(){}});
  assert.equal(g.root.findAllByType('Image').length,0,'Collapsed groups do not load QR images');
  await press(find(g,'guide-group-0')[0]);
  assert.equal(g.root.findAllByType('Image').length,1);
  await press(g.root.findAllByProps({accessibilityLabel:'查看原帖图片'})[0]);
  assert.equal(g.root.findAllByType('Modal').length,0,'Guide image viewer preserves parent navigation');
  await press(g.root.findByProps({accessibilityLabel:'关闭图片预览'}));
  assert.equal(find(g,'guide-group-0')[0].props.accessibilityState.expanded,true);
  await unmount(g);
  console.log('Guide reader passed: three languages, all 17 links, 17 sections, 7 steps/4 images, 46 food entries, 11 groups, search, navigation, inline images and post-end actions.');
}
run().catch(e=>{console.error(e);process.exitCode=1;});
